//! Descriptions for MS41 fault codes (BMW decimal codes, 1-255).
//!
//! Compiled from community lists that MS41, MS42 and MS43 share. Where a list
//! gives an MS43-only alternative meaning, the MS41/MS42 one is used here.
//! Not checked against BMW documentation, and some codes (electronic
//! throttle, CAN, secondary air) can't occur on an MS41 at all; they're kept so
//! an unexpected code still gets a name.

pub fn describe(code: u8) -> Option<&'static str> {
    CODES
        .binary_search_by_key(&code, |&(c, _)| c)
        .ok()
        .map(|i| CODES[i].1)
}

