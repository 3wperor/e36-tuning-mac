#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        assert!(CODES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn looks_up_codes() {
        assert_eq!(describe(10), Some("Coolant temperature sensor"));
        assert_eq!(describe(243), Some("Misfire, cylinder 6"));
        assert_eq!(describe(4), None);
    }
}
